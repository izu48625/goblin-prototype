import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const read=async p=>readFile(new URL('../'+p,import.meta.url),'utf8');
const root=await read('index.html');
const discover=await read('discover.html');
const ssr=await read('worker/seo.js');
const distRoot=await read('dist/index.html');
const distDiscover=await read('dist/discover.html');
assert.equal(root,distRoot,'Cloudflare bundle must ship original home HTML');
assert.equal(discover,distDiscover,'Cloudflare bundle must ship new Discover HTML');
assert(root.includes('id="basicFrame"')&&root.includes("src='base/index.html"),'Keep immediate iframe editor');
assert(root.includes('id="r87HomeGuide"')&&root.includes('<h1>採点をグラフ・ランキング・Tier表で見比べる</h1>'));
assert(root.includes('<summary>はじめての方へ')&&root.includes('href="/ja/use-cases.html"'));
assert(root.includes('href="/ja/scoring-guide.html"')&&root.includes('href="/ja/legal.html#contact"'));
assert(!root.includes('adsbygoogle.js')&&!root.includes('googletagmanager.com'));
assert(discover.includes('r87EditorialTitle')&&discover.includes('公式が作成した説明用サンプル'));
assert(discover.includes('下のユーザー公開作品とは別のコンテンツ'));
assert.equal((discover.match(/<a href="\/ja\/use-cases\.html#/g)||[]).length,3);
assert(discover.includes('id="grid"')&&discover.includes('id="moreBtn"'));
for(const x of ['cafe','routes','study'])assert(discover.includes('/ja/example-images/usecase-'+x+'.png'));
assert(ssr.includes('SEO_SCORE_ROWS=6,SEO_SCORE_COLUMNS=5'));
assert(ssr.includes("'seo_scores_'+i+':snapshot->rows->'+i+'->scores'"));
assert(ssr.includes("visibility:'eq.public'"),'Always retain exact Public visibility filter');
assert(ssr.includes("return response(html,'text/html; charset=utf-8',200,'no-store')"),'Public visibility switch must be immediately reflected');
assert(ssr.includes('scoreTable+'),'Actual read-only score excerpts not rendered in SSR');
assert(ssr.includes('Missing ratings')===false,'Do not add made-up text in HTML');
console.log('R87 static PASS: crawlable guide in real Home controls, official Discover samples, Public-only score SSR, user content untouched');
